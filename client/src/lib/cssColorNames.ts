/** Shortest completion first so typing narrows towards the obvious match. */
function byCompletionLength(a: string, b: string): number {
  return a.length - b.length || a.localeCompare(b)
}

/**
 * Named colours and keywords matching `query`, keywords first, prefix matches
 * ahead of mid-word matches. Empty while there is nothing to complete.
 */
export function suggestColorValues(query: string, limit = 5): string[] {
  const needle = query.trim().toLowerCase()
  if (!needle) return []

  const keywordPrefix: string[] = []
  const keywordInfix: string[] = []
  const namePrefix: string[] = []
  const nameInfix: string[] = []

  for (const keyword of COLOR_KEYWORDS) {
    const lower = keyword.toLowerCase()
    if (lower.startsWith(needle)) keywordPrefix.push(keyword)
    else if (lower.includes(needle)) keywordInfix.push(keyword)
  }

  for (const name of CSS_COLOR_NAMES) {
    if (name.startsWith(needle)) namePrefix.push(name)
    else if (name.includes(needle)) nameInfix.push(name)
  }

  namePrefix.sort(byCompletionLength)
  nameInfix.sort(byCompletionLength)

  return [...keywordPrefix, ...namePrefix, ...keywordInfix, ...nameInfix].slice(0, limit)
}
